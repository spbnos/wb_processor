def is_wb_detailed_columns(columns: list[str]) -> bool:
    """True если набор колонок похож на детализацию WB."""
    norms = [normalize(c) for c in columns]
    hits = sum(1 for m in _WB_FILE_MARKERS if any(m in n for n in norms))
    return hits >= 2


def is_wb_detailed_filename(name: str) -> bool:
    low = name.lower()
    return any(
        k in low
        for k in ("детализир", "ежедневн", "реализ", "отчет", "отчёт", "report")
    )


def match_wb_column(column: str) -> Optional[MatchResult]:
    """
  L0: словарь WB. Возвращает MatchResult или None (передать в generic matcher).
    """
    norm = normalize(column)
    if not norm:
        return None

    if norm in _WB_EXACT:
        field, score = _WB_EXACT[norm]
        method = "wb_ignore" if field == "ignore" else "wb_exact"
        return MatchResult(target_field=field, score=score, method=method)

    for phrase, field, score in _WB_SUBSTRING:
        if phrase in norm:
            method = "wb_ignore" if field == "ignore" else "wb_exact"
            return MatchResult(target_field=field, score=score, method=method)

    return None
